# Write src/44_art_img.js from built art folders: python3 -I make_js.py <out.js> <id>=<art dir> [...]
# Entries already in <out.js> that are not named again are kept as they are (each truck can be rebuilt on its own).
# A folder with a fix.json adds its fixtures (pictures any truck can carry, like the amber beacon) to ART_FIX.
import sys, json, os, re
out, pairs = sys.argv[1], [a.split('=', 1) for a in sys.argv[2:]]
entries, fixes = {}, {}
if os.path.exists(out):
    old = open(out).read()
    for m in re.finditer(r'^  (\w+): (\{.*\}),$', old, re.M):
        entries[m.group(1)] = m.group(2)
    fm = re.search(r'^const ART_FIX = (\{.*\});$', old, re.M)
    if fm: fixes = json.loads(fm.group(1))
    # entries inside ART_FIX were caught by the pattern above: keep only the trucks
    for k in list(entries):
        if k in fixes: del entries[k]
def r4(v): return round(v, 4) if isinstance(v, float) else v
def clean(o):
    if isinstance(o, dict): return {k: clean(v) for k, v in o.items() if k != 'px'}
    if isinstance(o, list): return [clean(v) for v in o]
    return r4(o)
for tid, d in pairs:
    meta = clean(json.load(open(d + '/meta.json'))); urls = json.load(open(d + '/urls.json'))
    meta.pop('ref', None)
    meta['src'] = urls
    entries[tid] = json.dumps(meta, separators=(',', ':'))
    if os.path.exists(d + '/fix.json'): fixes.update(clean(json.load(open(d + '/fix.json'))))
lines = ['// ===== drawn truck art: generated by tools/art/make_js.py from tools/art/build_art.py output, do not edit by hand =====',
         '// Each entry: body picture (wheel wells filled dark) and one picture per wheel, at ppm pixels per metre; x0/y1 is the',
         '// top-left corner of the body picture in the truck\'s frame (metres, y up), w/h its size. Magenta in the body is paint.',
         '// layers: add-on pictures placed the same way; zones: which paint takes the livery\'s second colour.',
         'const ART_IMG = {']
for tid, js in entries.items(): lines.append('  ' + tid + ': ' + js + ',')
lines.append('};')
lines.append('// fixtures any truck can carry, w/h in metres, standing on the middle of their bottom edge')
lines.append('const ART_FIX = ' + json.dumps(fixes, separators=(',', ':')) + ';')
# the bounds that frame a drawn truck in the workshop: its body, every add-on layer, and down to the ground
lines.append('for (const id in ART_IMG) { const A = ART_IMG[id], B0 = ART_BOUNDS[id]; let b = [A.x0, A.ground !== undefined ? A.ground - 0.02 : B0 ? B0[1] : A.y1 - A.h, A.x0 + A.w, A.y1]; '
             'for (const n in A.layers || {}) { const Ly = A.layers[n]; b = [Math.min(b[0], Ly.x0), Math.min(b[1], Ly.y1 - Ly.h), Math.max(b[2], Ly.x0 + Ly.w), Math.max(b[3], Ly.y1)]; } ART_BOUNDS[id] = b; }')
open(out, 'w').write('\n'.join(lines) + '\n')
print('wrote', out, 'trucks', list(entries), 'fixtures', list(fixes))
